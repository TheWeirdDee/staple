// Exports ABIs and linked-library bytecode from Foundry output into reference/src/abi.ts (shared by keeper,
// watcher tooling and web). Run after `forge build`: node contracts/script/export-abi.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'out');
const names = ['StapleDesk', 'MandateRegistry', 'TestFeeToken', 'QuoteEngine', 'DeskOrders', 'DeskAccounting'];
const load = (n) => JSON.parse(readFileSync(join(out, `${n}.sol`, `${n}.json`), 'utf8'));

// Library events are emitted from the desk's address via DELEGATECALL; merge them into the desk ABI.
const desk = load('StapleDesk');
const seen = new Set(desk.abi.filter((x) => x.type === 'event').map((x) => x.name));
for (const lib of ['DeskOrders']) {
  for (const item of load(lib).abi) {
    if ((item.type === 'event' || item.type === 'error') && !seen.has(item.name)) {
      desk.abi.push(item);
      seen.add(item.name);
    }
  }
}

let ts = '// GENERATED by contracts/script/export-abi.mjs from Foundry output. Do not edit.\n';
for (const n of names) {
  const j = n === 'StapleDesk' ? desk : load(n);
  ts += `export const ${n}Abi = ${JSON.stringify(j.abi)} as const;\n`;
  ts += `export const ${n}Bytecode = ${JSON.stringify(j.bytecode.object)} as const;\n`;
  const refs = j.bytecode.linkReferences ?? {};
  ts += `export const ${n}LinkReferences = ${JSON.stringify(refs)} as const;\n`;
}
writeFileSync(join(here, '..', '..', 'reference', 'src', 'abi.ts'), ts);
console.log('wrote reference/src/abi.ts');
