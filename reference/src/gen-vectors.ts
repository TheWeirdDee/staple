/**
 * Generates the frozen quote vectors (reference/vectors/quote-vectors.json) and the Solidity test that replays
 * them against the on-chain QuoteEngine (contracts/test/QuoteVectors.t.sol).
 *
 * Run only when deliberately changing quote semantics: `pnpm vectors`. The TS test suite fails if the
 * committed JSON no longer matches this reference.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildVectors } from './vectors.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const v = buildVectors();

const json = JSON.stringify(v, (_k, val) => (typeof val === 'bigint' ? val.toString() : val), 2);
writeFileSync(join(root, 'reference', 'vectors', 'quote-vectors.json'), json + '\n');

const b = (x: boolean) => (x ? 'true' : 'false');
const lines: string[] = [];
lines.push('// SPDX-License-Identifier: MIT');
lines.push('// GENERATED by reference/src/gen-vectors.ts from reference/vectors/quote-vectors.json. Do not edit.');
lines.push('pragma solidity 0.8.28;');
lines.push('');
lines.push('import {QuoteEngine} from "../src/QuoteEngine.sol";');
lines.push('import {MarketParams, QuoteParams, ExposureParams, BookRule} from "../src/StapleTypes.sol";');
lines.push('import {TestBase} from "./TestBase.sol";');
lines.push('');
lines.push('contract QuoteVectorsTest is TestBase {');

lines.push('    function test_tickVectors() public pure {');
for (const t of v.ticks) {
  lines.push(
    `        assertEqU(QuoteEngine.roundPx(${t.pxE8}, ${t.szDecimals}, ${b(t.isSpot)}, false), ${t.down}, "${t.name} down");`,
  );
  lines.push(
    `        assertEqU(QuoteEngine.roundPx(${t.pxE8}, ${t.szDecimals}, ${b(t.isSpot)}, true), ${t.up}, "${t.name} up");`,
  );
}
lines.push('    }');
lines.push('');

lines.push('    function test_healthyVectors() public pure {');
for (const h of v.healthy) {
  lines.push(
    `        assertTrue(QuoteEngine.isHealthy(${h.bid}, ${h.ask}, ${h.bidDepth}, ${h.askDepth}, ${h.spreadBps}, ${h.sizeLots}) == ${b(h.expected)}, "${h.name}");`,
  );
}
lines.push('    }');
lines.push('');

v.ladders.forEach((l, idx) => {
  const i = l.input;
  lines.push(`    /// ${l.name}`);
  lines.push(`    function test_ladder_${idx}() public pure {`);
  lines.push('        QuoteEngine.LadderInput memory inp;');
  lines.push(`        inp.midE8 = ${i.midE8};`);
  lines.push(`        inp.inventoryE8 = ${i.inventoryE8};`);
  lines.push(`        inp.extBestBidE8 = ${i.extBestBidE8};`);
  lines.push(`        inp.extBestAskE8 = ${i.extBestAskE8};`);
  lines.push(`        inp.healthy = ${b(i.healthy)};`);
  lines.push(
    `        inp.market = MarketParams(${i.market.asset}, ${i.market.szDecimals}, ${b(i.market.isSpot)}, ${i.market.minNotionalE8});`,
  );
  lines.push(
    `        inp.quotes = QuoteParams(${i.quotes.spreadBps}, ${i.quotes.levels}, ${i.quotes.levelSpacingBps}, ${i.quotes.sizeLots}, ${i.quotes.skewBps}, ${i.quotes.requoteBps}, BookRule.${i.quotes.bookRule});`,
  );
  const e = i.exposure;
  lines.push(
    `        inp.exposure = ExposureParams(${e.baselineBaseE8}, ${e.minBaseE8}, ${e.maxBaseE8}, ${e.quoteBudgetE8}, ${e.maxOutstandingNotionalE8}, ${e.feeAllowanceBps});`,
  );
  lines.push('        QuoteEngine.Ladder memory out = QuoteEngine.ladder(inp);');
  lines.push(`        assertEqU(out.reservationE8, ${l.expected.reservationE8}, "reservation");`);
  lines.push(`        assertEqI(out.skewBps, ${l.expected.skewBps}, "skew");`);
  l.expected.bids.forEach((lv, k) => {
    lines.push(`        assertEqU(out.bids[${k}].pxE8, ${lv.pxE8}, "bid${k} px");`);
    lines.push(`        assertEqU(out.bids[${k}].szLots, ${lv.szLots}, "bid${k} sz");`);
    lines.push(`        assertTrue(out.bids[${k}].valid == ${b(lv.valid)}, "bid${k} valid");`);
  });
  l.expected.asks.forEach((lv, k) => {
    lines.push(`        assertEqU(out.asks[${k}].pxE8, ${lv.pxE8}, "ask${k} px");`);
    lines.push(`        assertEqU(out.asks[${k}].szLots, ${lv.szLots}, "ask${k} sz");`);
    lines.push(`        assertTrue(out.asks[${k}].valid == ${b(lv.valid)}, "ask${k} valid");`);
  });
  lines.push('    }');
  lines.push('');
});

lines.push('    function test_reservationVectors() public pure {');
lines.push('        QuoteEngine.Reserved memory nx;');
lines.push('        bool ok;');
v.reservations.forEach((r) => {
  const e = r.exposure;
  lines.push(`        // ${r.name}`);
  lines.push(
    `        (ok, nx) = QuoteEngine.reservationFits(QuoteEngine.Reserved(${r.t.buyLots}, ${r.t.sellLots}, ${r.t.buyQuoteE8}, ${r.t.notionalE8}), ${r.baseBalE8}, ${r.quoteBalE8}, ${b(r.isBuy)}, ${r.pxE8}, ${r.lots}, ${r.szDecimals}, ExposureParams(${e.baselineBaseE8}, ${e.minBaseE8}, ${e.maxBaseE8}, ${e.quoteBudgetE8}, ${e.maxOutstandingNotionalE8}, ${e.feeAllowanceBps}));`,
  );
  lines.push(`        assertTrue(ok == ${b(r.expected.ok)}, "${r.name} ok");`);
  lines.push(`        assertEqU(nx.buyLots, ${r.expected.next.buyLots}, "${r.name} buyLots");`);
  lines.push(`        assertEqU(nx.sellLots, ${r.expected.next.sellLots}, "${r.name} sellLots");`);
  lines.push(`        assertEqU(nx.buyQuoteE8, ${r.expected.next.buyQuoteE8}, "${r.name} buyQuote");`);
  lines.push(`        assertEqU(nx.notionalE8, ${r.expected.next.notionalE8}, "${r.name} notional");`);
});
lines.push('    }');
lines.push('}');
writeFileSync(join(root, 'contracts', 'test', 'QuoteVectors.t.sol'), lines.join('\n') + '\n');
console.log(
  `wrote ${v.ticks.length} tick, ${v.healthy.length} healthy, ${v.ladders.length} ladder, ${v.reservations.length} reservation vectors`,
);
